"""Supabase-only journal for continuous hourly weather paper trading."""
import json
import os
from datetime import datetime, timezone

from src.database.db import get_connection

STRATEGY = "HOURLY_CONTINUOUS_30_5_V1"
TABLE = "prediction_bot.hourly_continuous_shadow_journal"


class SupabaseJournal:
    def __init__(self):
        url = os.environ.get("PREDICTION_DATABASE_URL", "")

        if not url.startswith((
            "postgresql://",
            "postgres://",
            "postgresql+psycopg://",
        )):
            raise RuntimeError(
                "Supabase PostgreSQL connection required. "
                "Refusing local database fallback."
            )

        self.traded = set()
        self.open_positions = {}

        with get_connection() as con:
            with con.cursor() as cur:
                cur.execute(f"""
                    CREATE TABLE IF NOT EXISTS {TABLE} (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY
                            PRIMARY KEY,
                        recorded_at_utc TIMESTAMPTZ NOT NULL
                            DEFAULT NOW(),
                        strategy TEXT NOT NULL,
                        event_ticker TEXT,
                        kind TEXT NOT NULL,
                        payload JSONB NOT NULL
                    )
                """)

                cur.execute(f"""
                    CREATE INDEX IF NOT EXISTS
                        ix_hourly_cont_shadow_journal_recovery
                    ON {TABLE} (strategy, kind, id)
                """)

                cur.execute(f"""
                    CREATE UNIQUE INDEX IF NOT EXISTS
                        ix_hourly_cont_shadow_one_entry
                    ON {TABLE} (strategy, event_ticker)
                    WHERE kind = 'PAPER_ENTRY'
                """)

        self.recover()

    def recover(self):
        with get_connection() as con:
            with con.cursor() as cur:
                cur.execute(f"""
                    SELECT kind, payload::text
                    FROM {TABLE}
                    WHERE strategy = %s
                      AND kind IN ('PAPER_ENTRY', 'SETTLED')
                    ORDER BY id
                """, (STRATEGY,))

                for kind, payload in cur.fetchall():
                    row = json.loads(payload)
                    event = row.get("event")

                    if kind == "PAPER_ENTRY":
                        self.traded.add(event)
                        self.open_positions[event] = row

                    elif kind == "SETTLED":
                        self.open_positions.pop(event, None)

    def record(self, kind, **fields):
        row = {
            "strategy": STRATEGY,
            "recorded_at_utc": datetime.now(
                timezone.utc
            ).isoformat(),
            "kind": kind,
            **fields,
        }

        payload = json.dumps(
            row, default=str, allow_nan=False
        )

        # Fail closed: a database error must not silently
        # become a local-only paper trade.
        with get_connection() as con:
            with con.cursor() as cur:
                cur.execute(f"""
                    INSERT INTO {TABLE}
                        (strategy, event_ticker, kind, payload)
                    VALUES (%s, %s, %s, %s::jsonb)
                """, (
                    STRATEGY,
                    row.get("event"),
                    kind,
                    payload,
                ))

        if kind == "PAPER_ENTRY":
            self.traded.add(row["event"])
            self.open_positions[row["event"]] = row

        elif kind == "SETTLED":
            self.open_positions.pop(row["event"], None)
