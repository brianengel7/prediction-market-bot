"""Import the local SQLite database into an empty Supabase schema."""

import argparse
import getpass
import os
import re
import sqlite3
from contextlib import closing
from pathlib import Path


SQLITE_PATH = Path(__file__).with_name("prediction_market.db")

EXPECTED_TABLES = {
    "historical_market_entries",
    "live_orders",
    "market_edge_snapshots",
    "market_snapshots",
    "model_snapshots",
    "v2_market_only_shadow_decisions",
    "v2_nbm_probabilities",
    "v2_shadow_trades",
    "weather_actuals",
    "weather_backtests",
    "weather_fair_values",
    "weather_forecasts",
    "weather_model_backtests",
}


def postgres_ddl(sqlite_ddl):
    ddl = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sqlite_ddl,
        flags=re.IGNORECASE,
    )
    ddl = re.sub(
        r"\bREAL\b",
        "DOUBLE PRECISION",
        ddl,
        flags=re.IGNORECASE,
    )
    if re.search(r"\bAUTOINCREMENT\b", ddl, re.IGNORECASE):
        raise RuntimeError("Unconverted SQLite AUTOINCREMENT in schema.")
    return ddl


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Import into an empty Supabase prediction_bot schema",
    )
    args = parser.parse_args()

    if not SQLITE_PATH.is_file():
        raise RuntimeError(f"SQLite database not found: {SQLITE_PATH}")

    readonly_uri = SQLITE_PATH.resolve().as_uri() + "?mode=ro"

    with closing(sqlite3.connect(readonly_uri, uri=True)) as local:
        with closing(sqlite3.connect(":memory:")) as snapshot:
            local.backup(snapshot)

            check = snapshot.execute("PRAGMA integrity_check").fetchone()[0]
            if check != "ok":
                raise RuntimeError(f"SQLite integrity check failed: {check}")

            tables = snapshot.execute(
                "SELECT name, sql FROM sqlite_master "
                "WHERE type = 'table' AND name NOT LIKE 'sqlite_%' "
                "ORDER BY name"
            ).fetchall()

            names = {name for name, _ in tables}
            if names != EXPECTED_TABLES:
                raise RuntimeError(
                    f"Unexpected tables. Missing: {EXPECTED_TABLES - names}; "
                    f"extra: {names - EXPECTED_TABLES}"
                )

            counts = {}
            for name, _ in tables:
                counts[name] = snapshot.execute(
                    f'SELECT COUNT(*) FROM "{name}"'
                ).fetchone()[0]
                print(f"{name}: {counts[name]} SQLite rows")

            if not args.apply:
                print("Inspection only; no Supabase changes.")
                return

            import psycopg
            from psycopg import sql

            url = os.environ.get("PREDICTION_DATABASE_URL")
            if not url:
                url = getpass.getpass("Supabase Session pooler URI: ")

            with psycopg.connect(
                url,
                sslmode="require",
                connect_timeout=20,
                prepare_threshold=None,
            ) as remote:
                remote.execute(
                    "CREATE SCHEMA IF NOT EXISTS prediction_bot"
                )

                existing = remote.execute(
                    "SELECT COUNT(*) FROM pg_catalog.pg_tables "
                    "WHERE schemaname = 'prediction_bot'"
                ).fetchone()[0]
                if existing:
                    raise RuntimeError(
                        "prediction_bot already has tables; "
                        "this import requires an empty schema."
                    )

                remote.execute(
                    "SET search_path TO prediction_bot, public"
                )

                for _, sqlite_ddl in tables:
                    remote.execute(postgres_ddl(sqlite_ddl))

                for name, _ in tables:
                    columns = [
                        row[1]
                        for row in snapshot.execute(
                            f'PRAGMA table_info("{name}")'
                        )
                    ]
                    table = sql.Identifier(name)
                    fields = sql.SQL(", ").join(
                        sql.Identifier(column) for column in columns
                    )

                    with remote.cursor() as cursor:
                        copy_query = sql.SQL(
                            "COPY {} ({}) FROM STDIN"
                        ).format(table, fields)

                        with cursor.copy(copy_query) as writer:
                            for row in snapshot.execute(
                                f'SELECT * FROM "{name}"'
                            ):
                                writer.write_row(row)

                        if "id" in columns and counts[name]:
                            cursor.execute(
                                sql.SQL(
                                    "SELECT setval("
                                    "pg_get_serial_sequence(%s, 'id'), "
                                    "(SELECT MAX(id) FROM {}), true)"
                                ).format(table),
                                (f"prediction_bot.{name}",),
                            )

                        copied = cursor.execute(
                            sql.SQL("SELECT COUNT(*) FROM {}").format(table)
                        ).fetchone()[0]

                    if copied != counts[name]:
                        raise RuntimeError(
                            f"{name}: expected {counts[name]}, found {copied}"
                        )
                    print(f"{name}: verified {copied} Supabase rows")

            print("Import committed successfully.")


if __name__ == "__main__":
    main()